// String returns the symbolic name of an opcode, or "<opcode N>".
func (o Opcode) String() string {
	if s, ok := names[o]; ok {
		return s
	}
	return "<opcode " + itoa(int(o)) + ">"
}

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	neg := n < 0
	if neg {
		n = -n
	}
	var b [20]byte
	i := len(b)
	for n > 0 {
		i--
		b[i] = byte('0' + n%10)
		n /= 10
	}
	if neg {
		i--
		b[i] = '-'
	}
	return string(b[i:])
}
